import * as argon2 from 'argon2';
import * as jwt from 'jsonwebtoken';
import type { Pool, ResultSetHeader, RowDataPacket } from 'mysql2/promise';
import { config } from './config';

export interface AuthUser {
  id: number;
  username: string;
  displayName: string;
}

export class AuthError extends Error {
  constructor(message: string, public status = 400) {
    super(message);
  }
}

/** "Nguyễn Văn Đạt" -> "nguyenvandat" (ASCII, max 14 chars). */
export function slugify(name: string): string {
  const s = name
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/đ/g, 'd')
    .replace(/Đ/g, 'D')
    .toLowerCase()
    .replace(/[^a-z0-9]/g, '')
    .slice(0, 14);
  return s || 'player';
}

export function cleanDisplayName(raw: unknown): string {
  if (typeof raw !== 'string') throw new AuthError('Tên hiển thị không hợp lệ.');
  const name = raw.replace(/\s+/g, ' ').trim();
  // eslint-disable-next-line no-control-regex
  if (name.length < 1 || name.length > 24 || /[\u0000-\u001f\u007f<>]/.test(name)) throw new AuthError('Tên hiển thị cần từ 1 đến 24 ký tự (không dùng ký tự đặc biệt < >).');
  return name;
}

export function cleanPassword(raw: unknown): string {
  if (typeof raw !== 'string' || raw.length < 6 || raw.length > 128) throw new AuthError('Mật khẩu cần từ 6 đến 128 ký tự.');
  return raw;
}

const ARGON: argon2.Options = { type: argon2.argon2id, memoryCost: 19456, timeCost: 2, parallelism: 1 };
let dummyHash: Promise<string> | null = null;

export class AuthService {
  constructor(private pool: Pool) {}

  private sign(u: AuthUser): string {
    return jwt.sign({ sub: String(u.id), un: u.username, dn: u.displayName }, config.jwtSecret, {
      algorithm: 'HS256',
      expiresIn: `${config.jwtDays}d`,
    });
  }

  verify(token: unknown): AuthUser | null {
    if (typeof token !== 'string' || token.length > 2000) return null;
    try {
      const p = jwt.verify(token, config.jwtSecret, { algorithms: ['HS256'] }) as jwt.JwtPayload;
      const id = Number(p.sub);
      if (!Number.isInteger(id) || typeof p.un !== 'string' || typeof p.dn !== 'string') return null;
      return { id, username: p.un, displayName: p.dn };
    } catch {
      return null;
    }
  }

  /** Display name + password -> a unique username generated by the system (shown once after registering). */
  async register(displayNameRaw: unknown, passwordRaw: unknown): Promise<{ user: AuthUser; token: string }> {
    const displayName = cleanDisplayName(displayNameRaw);
    const password = cleanPassword(passwordRaw);
    const hash = await argon2.hash(password, ARGON);
    const base = slugify(displayName);
    for (let attempt = 0; attempt < 12; attempt++) {
      const digits = attempt < 6 ? 4 : 6;
      const suffix = String(Math.floor(Math.random() * 10 ** digits)).padStart(digits, '0');
      const username = `${base}-${suffix}`;
      try {
        const [res] = await this.pool.execute<ResultSetHeader>(
          'INSERT INTO users (username, display_name, password_hash) VALUES (?, ?, ?)',
          [username, displayName, hash]
        );
        const user = { id: Number(res.insertId), username, displayName };
        return { user, token: this.sign(user) };
      } catch (e) {
        if ((e as { code?: string }).code === 'ER_DUP_ENTRY') continue;
        throw e;
      }
    }
    throw new AuthError('Không tạo được username, thử lại nhé.', 503);
  }

  async login(usernameRaw: unknown, passwordRaw: unknown): Promise<{ user: AuthUser; token: string }> {
    const bad = new AuthError('Sai username hoặc mật khẩu.', 401);
    if (typeof usernameRaw !== 'string' || typeof passwordRaw !== 'string' || usernameRaw.length > 40 || passwordRaw.length > 128) throw bad;
    const [rows] = await this.pool.execute<RowDataPacket[]>('SELECT id, username, display_name, password_hash FROM users WHERE username = ?', [
      usernameRaw.trim().toLowerCase(),
    ]);
    const row = rows[0];
    if (!row) {
      // spend the same time as a real check so usernames cannot be probed by timing
      dummyHash ??= argon2.hash('dummy-password', ARGON);
      await argon2.verify(await dummyHash, passwordRaw).catch(() => false);
      throw bad;
    }
    const okPw = await argon2.verify(String(row.password_hash), passwordRaw).catch(() => false);
    if (!okPw) throw bad;
    const user = { id: Number(row.id), username: String(row.username), displayName: String(row.display_name) };
    return { user, token: this.sign(user) };
  }
}
